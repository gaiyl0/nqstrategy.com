import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import path from 'node:path';
import {parseEcbUsdCnyRate,fetchEcbUsdCnyRate,ECB_DAILY_RATES_URL} from '../lib/ecb-recharge-rate.mjs';

const now=Date.now();
const date=new Date(now-60*60*1000).toISOString().slice(0,10);
const xml=(published=date,usd='1.1000',cny='7.5000')=>`<?xml version="1.0"?><gesmes:Envelope><gesmes:name>European Central Bank</gesmes:name><Cube><Cube time='${published}'><Cube currency='USD' rate='${usd}'/><Cube currency='CNY' rate='${cny}'/></Cube></Cube></gesmes:Envelope>`;
const parsed=parseEcbUsdCnyRate(xml(),now);
assert.equal(parsed.cnyFenPerUsd,682);
assert.equal(parsed.publishedDate,date);
assert.throws(()=>parseEcbUsdCnyRate(xml(new Date(now-6*86400000).toISOString().slice(0,10)),now),/RECHARGE_RATE_FEED_INVALID/);
assert.throws(()=>parseEcbUsdCnyRate(xml(date,'0','7.5000'),now),/RECHARGE_RATE_FEED_INVALID/);
assert.throws(()=>parseEcbUsdCnyRate(xml(date,'1.1',''),now),/RECHARGE_RATE_FEED_INVALID/);
let fetched=0;
const fetchImpl=async(url,options)=>{
  fetched++;
  assert.equal(url,ECB_DAILY_RATES_URL);
  assert.equal(options.redirect,'error');
  return new Response(xml(),{status:200,headers:{'Content-Type':'text/xml'}});
};
assert.equal((await fetchEcbUsdCnyRate(fetchImpl,now)).cnyFenPerUsd,682);

process.env.NEXUS_DB_PATH=path.resolve(`.tmp-ecb-rate-${crypto.randomUUID()}.db`);
process.env.NEXUS_AUTO_MIGRATE='1';
const {default:db}=await import('../lib/db.js');
const {configuredRechargeExchangeRate,createPointRechargeOrder,rechargeRateDetails,refreshAutomaticRechargeRate,setRechargeExchangeRate,setRechargeRateMode}=await import('../lib/point-recharge.js');
assert.equal(rechargeRateDetails(now).mode,'auto');
assert.equal(rechargeRateDetails(now).cnyFenPerUsd,null);
const first=await refreshAutomaticRechargeRate({fetchImpl,now});
assert.equal(first.cnyFenPerUsd,682);
assert.equal(first.referenceDate,date);
assert.equal(configuredRechargeExchangeRate(),682);
await refreshAutomaticRechargeRate({fetchImpl,now:now+30000});
assert.equal(fetched,2,'rate must be cached between checks');
const fallback=await refreshAutomaticRechargeRate({force:true,fetchImpl:async()=>{throw new Error('offline');},now:now+60000});
assert.equal(fallback.feedUnavailable,true);
assert.equal(fallback.cnyFenPerUsd,682);
const userId=Number(db.prepare("INSERT INTO users(username,email,role,password) VALUES('fx-buyer','fx-buyer@example.com','user','hash')").run().lastInsertRowid);
const order=createPointRechargeOrder(userId,10,'wechat',crypto.randomUUID(),now);
assert.equal(order.cnyFen,6820);
assert.equal(order.cnyFenPerUsd,682);
assert.equal(setRechargeExchangeRate(725),725);
assert.equal(rechargeRateDetails().mode,'manual');
assert.equal(configuredRechargeExchangeRate(),725);
await refreshAutomaticRechargeRate({force:true,fetchImpl:async()=>{throw new Error('must not fetch');},now});
assert.equal(db.prepare('SELECT cny_fen FROM point_recharge_orders WHERE id=?').get(order.id).cny_fen,6820,'existing quote remains locked');
setRechargeRateMode('auto');
assert.equal(rechargeRateDetails(now).cnyFenPerUsd,null,'manual value cannot become an automatic fallback');
await assert.rejects(refreshAutomaticRechargeRate({force:true,fetchImpl:async()=>{throw new Error('offline');},now}),/offline/);
assert.equal(rechargeRateDetails(now).cnyFenPerUsd,null);
await refreshAutomaticRechargeRate({force:true,fetchImpl,now});
assert.equal(rechargeRateDetails().mode,'auto');
console.log('ECB exchange-rate tests passed: cross rate, stale/invalid feed rejection, cache, outage fallback, manual override and order quote lock');
db.close();
